-- 시연용 조회 SQL (Oracle)
-- 지원자는 APPLICANT_KEY로 구분한다. ORDER_TB.NAME은 주문자 이름이라 지원자 이름 컬럼은 없다.
-- :applicant_key 에 과제 API 응답의 APPLICANT_KEY 값을 넣어 실행한다.
-- 당일 기준: CREATE_TIME, CREATE_DATE는 INSERT 시 DB 기본값 SYSDATE로 채워진다.

-- 1. 당일 처리 요약 (주문 건수, 배송 등록 건수, 미배송 건수)
SELECT COUNT(*)                                  AS ORDER_CNT,
       SUM(CASE WHEN O.STATUS = 'Y' THEN 1 ELSE 0 END) AS SHIPPED_CNT,
       SUM(CASE WHEN O.STATUS = 'N' THEN 1 ELSE 0 END) AS PENDING_CNT
  FROM ORDER_TB O
 WHERE O.APPLICANT_KEY = :applicant_key
   AND O.CREATE_TIME >= TRUNC(SYSDATE);

-- 2. 당일 주문 목록
SELECT O.ORDER_ID, O.USER_ID, O.ITEM_ID, O.NAME, O.ADDRESS, O.ITEM_NAME, O.PRICE, O.STATUS, O.CREATE_TIME
  FROM ORDER_TB O
 WHERE O.APPLICANT_KEY = :applicant_key
   AND O.CREATE_TIME >= TRUNC(SYSDATE)
 ORDER BY O.ORDER_ID;

-- 3. 당일 배송 목록
SELECT S.SHIPMENT_ID, S.ORDER_ID, S.ITEM_ID, S.ADDRESS, S.CREATE_DATE
  FROM SHIPMENT_TB S
 WHERE S.APPLICANT_KEY = :applicant_key
   AND S.CREATE_DATE >= TRUNC(SYSDATE)
 ORDER BY S.SHIPMENT_ID;

-- 4. 주문과 배송 대조 (전체 기간). 배송이 없거나 STATUS가 맞지 않는 주문만 나온다. 정상이면 0건
SELECT O.ORDER_ID, O.STATUS, S.SHIPMENT_ID
  FROM ORDER_TB O
  LEFT JOIN SHIPMENT_TB S
    ON S.APPLICANT_KEY = O.APPLICANT_KEY
   AND S.ORDER_ID = O.ORDER_ID
 WHERE O.APPLICANT_KEY = :applicant_key
   AND ((O.STATUS = 'Y' AND S.SHIPMENT_ID IS NULL)
     OR (O.STATUS = 'N' AND S.SHIPMENT_ID IS NOT NULL))
 ORDER BY O.ORDER_ID;
